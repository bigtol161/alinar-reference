class Command(BaseCommand):
    help = 'Заполняет базу демо-данными агрегатора НадоТУТ'

    def handle(self, *args, **options):
        Review.objects.all().delete()
        Service.objects.all().delete()
        Master.objects.all().delete()
        Category.objects.all().delete()
        District.objects.all().delete()

        districts = {}
        for name in DISTRICTS:
            districts[name] = District.objects.create(name=name)

        categories = {}
        for name, short, slug, icon, description, order in CATEGORIES:
            categories[slug] = Category.objects.create(
                name=name, short=short, slug=slug, icon=icon,
                description=description, sort_order=order,
            )

        now = timezone.now()
        for md in MASTERS:
            master = Master.objects.create(
                name=md['name'],
                slug=md['slug'],
                category=categories[md['cat']],
                title=md['title'],
                price_from=md['price_from'],
                rating=md['rating'],
                reviews_count=md['reviews_count'],
                experience=md['exp'],
                verified=md['verified'],
                online=md['online'],
                completed=md['completed'],
                phone=md['phone'],
                about=md['about'],
            )
            master.districts.set(districts[d] for d in md['districts'] if d in districts)
            for i, (sname, sprice) in enumerate(md['services'], 1):
                Service.objects.create(master=master, name=sname, price=sprice, sort_order=i)
            for author, rating, days_ago, text in md['reviews']:
                Review.objects.create(
                    master=master, author=author, rating=rating, text=text,
                    created_at=now - timedelta(days=days_ago),
                )

        self.stdout.write(self.style.SUCCESS(
            'Готово: категорий {}, районов {}, мастеров {}, отзывов {}'.format(
                Category.objects.count(), District.objects.count(),
                Master.objects.count(), Review.objects.count(),
            )
        ))
